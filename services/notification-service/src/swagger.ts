import type { INestApplication } from '@nestjs/common';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';

export function configureSwagger(app: INestApplication): void {
  const config = new DocumentBuilder()
    .setTitle('WGO Notification Service HTTP API')
    .setDescription(
      'Notification inbox, FCM registration, preferences, board preferences and nearby subscriptions. Frontend clients use the HTTP Gateway with Authorization: Bearer <user Access JWT>; internal identity headers and service tokens are generated by the Gateway. This service document describes the internal hop: production requires a signed Gateway service JWT plus X-User-Id; local/test requests without Authorization may use X-User-Id directly. The integrated Gateway Swagger replaces this internal authentication with user Bearer authentication and excludes health APIs. Obtain FCM tokens with the Firebase SDK, register/refresh per device, and unregister before logout. Push delivery is a hint: refresh the inbox and unread count, and use notificationId to correlate push data with inbox items. Error bodies from this service use statusCode/message and optional error; Gateway errors use code/message/requestId/timestamp.',
    )
    .setVersion('1.0.0')
    .addBearerAuth(
      {
        type: 'http',
        scheme: 'bearer',
        bearerFormat: 'Gateway service JWT (ES256)',
        description:
          'Internal signed HTTP Gateway token. Frontend clients use their user Access JWT at the Gateway instead.',
      },
      'GatewayBearer',
    )
    .build();
  SwaggerModule.setup(
    'docs',
    app,
    () => SwaggerModule.createDocument(app, config),
    { jsonDocumentUrl: 'docs/openapi.json' },
  );
}
