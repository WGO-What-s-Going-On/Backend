import { applyDecorators } from '@nestjs/common';
import {
  ApiHeader,
  ApiProperty,
  ApiPropertyOptional,
  ApiResponse,
} from '@nestjs/swagger';
import type { KakaoLoginResponse } from './auth/dto/kakao-login-response.dto.js';
import type { RefreshResponse } from './auth/dto/refresh-response.dto.js';
import { UserStatus } from './database/entities/user.entity.js';
import type { NicknameAvailabilityResponse } from './users/dto/nickname-availability-response.dto.js';
import type { UserProfileResponse } from './users/dto/user-profile.dto.js';
import type { TermConsentsResponse } from './users/dto/term-consents.dto.js';
import type { UserBadgesResponse } from './users/dto/user-badges-response.dto.js';
import type { WithdrawalResponse } from './users/dto/withdrawal-response.dto.js';
import type {
  TermResponse,
  TermsResponse,
} from './terms/dto/terms-response.dto.js';

// Schema-only models: controllers keep their existing manual input validation.
export class RefreshResult implements RefreshResponse {
  @ApiProperty({
    description:
      'Issued user Access JWT; the current HTTP Gateway does not validate it.',
  })
  accessToken!: string;
  @ApiProperty({
    description:
      'Opaque sessionId.secret token. Rotate using the refresh endpoint.',
  })
  refreshToken!: string;
  @ApiProperty({
    type: 'integer',
    description:
      'Access token lifetime in seconds; configured by JWT_ACCESS_TTL_SECONDS.',
  })
  expiresIn!: number;
}
export class KakaoLoginResult
  extends RefreshResult
  implements KakaoLoginResponse
{
  @ApiProperty({
    example: '123',
    description: 'Positive decimal string, at most 9007199254740991.',
  })
  userId!: string;
  @ApiProperty() isNewUser!: boolean;
  @ApiProperty() onboardingRequired!: boolean;
  @ApiProperty({
    description:
      'True only when this login restored the account before its withdrawal deadline.',
  })
  restoredFromWithdrawal!: boolean;
}
export class UserProfileResult implements UserProfileResponse {
  @ApiProperty({
    type: String,
    nullable: true,
    description: 'Private: only returned in own profile',
  })
  realName!: string | null;
  @ApiProperty({ example: '123' }) userId!: string;
  @ApiProperty() nickname!: string;
  @ApiProperty({ type: String, nullable: true }) profileImageKey!:
    | string
    | null;
  @ApiProperty({ enum: UserStatus }) status!: UserStatus;
  @ApiProperty() onboardingRequired!: boolean;
  @ApiProperty({ format: 'date-time' }) createdAt!: string;
}
export class NicknameAvailabilityResult
  implements NicknameAvailabilityResponse
{
  @ApiProperty() available!: boolean;
  @ApiProperty({
    type: String,
    enum: ['DUPLICATED'],
    nullable: true,
    description:
      'Currently only duplication is checked; available names return null.',
  })
  reason!: 'DUPLICATED' | null;
}
export class TermConsentsResult implements TermConsentsResponse {
  @ApiProperty({
    type: [String],
    description: 'Canonical string IDs, deduplicated in first-input order.',
    example: ['1', '2'],
  })
  termIds!: string[];
}
type BadgeResult = UserBadgesResponse['badges'][number];
class UserBadge implements BadgeResult {
  @ApiProperty() badgeId!: string;
  @ApiProperty() code!: string;
  @ApiProperty() name!: string;
  @ApiProperty({ type: String, nullable: true }) description!: string | null;
  @ApiProperty({ type: String, nullable: true }) imageKey!: string | null;
  @ApiProperty({ format: 'date-time' }) grantedAt!: string;
}
export class UserBadgesResult implements UserBadgesResponse {
  @ApiProperty({ type: [UserBadge] }) badges!: UserBadge[];
}
export class WithdrawalResult implements WithdrawalResponse {
  @ApiProperty({ enum: ['WITHDRAWAL_PENDING'] }) status!: 'WITHDRAWAL_PENDING';
  @ApiProperty({
    format: 'date-time',
    description:
      'Exactly 30 days after initial request. Repeated requests preserve the deadline.',
  })
  recoverableUntil!: string;
}
class Term implements TermResponse {
  @ApiProperty() termId!: string;
  @ApiProperty() code!: string;
  @ApiProperty() version!: string;
  @ApiProperty() required!: boolean;
  @ApiProperty() documentUrl!: string;
  @ApiProperty({ format: 'date-time' }) effectiveAt!: string;
}
export class TermsResult implements TermsResponse {
  @ApiProperty({ type: [Term] }) terms!: Term[];
}
export class UserHttpError {
  @ApiProperty({ type: 'integer' }) statusCode!: number;
  @ApiProperty() message!: string;
  @ApiPropertyOptional() error?: string;
}
export class UserLiveness {
  @ApiProperty({ enum: ['user-service'] }) service!: string;
  @ApiProperty({ enum: ['ok'] }) status!: string;
}

export function userIdentityHeader() {
  return ApiHeader({
    name: 'X-User-Id',
    required: true,
    description:
      'Internal context generated by the authenticated HTTP Gateway from the verified user JWT sub. Public clients must not supply this header.',
    schema: {
      type: 'string',
      pattern: '^[1-9][0-9]*$',
      example: '123',
      description:
        'Positive decimal ID, no leading zero, at most 9007199254740991.',
    },
  });
}
export function userErrorResponses(...responses: Array<[number, string]>) {
  return applyDecorators(
    ...responses.map(([status, description]) =>
      ApiResponse({ status, description, type: UserHttpError }),
    ),
  );
}
