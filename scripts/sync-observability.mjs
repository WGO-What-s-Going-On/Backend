import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { services } from './ci-lib.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
for (const service of services) {
  const files = [
    'logging.ts',
    ...(service.name.endsWith('-gateway') || service.name === 'map-service'
      ? []
      : ['nest.ts']),
  ];
  for (const name of files) {
    const source = resolve(root, 'shared/observability', name);
    if (!existsSync(source))
      throw new Error(`Missing canonical logging source: ${name}`);
    const target = resolve(root, service.path, 'src/observability', name);
    const content =
      '// Generated by scripts/sync-observability.mjs. Edit shared/observability instead.\n' +
      readFileSync(source, 'utf8');
    if (check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== content)
        throw new Error(`Logging source drift: ${target}`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
}
